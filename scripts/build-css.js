'use strict';

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const cssDir = path.join(rootDir, 'public', 'css');
const modulesDir = path.join(cssDir, 'modules');

const modules = {
    foundation: '00-foundation.css',
    solarShowcase: '10-solar-showcase.css',
    homeSections: '20-home-sections.css',
    sharedTail: '30-shared-components.css',
    homeThemeMain: '40-theme-home.css',
    sharedFaq: '45-shared-faq.css',
    homeThemeFooter: '47-theme-home-footer.css',
    homeSolarResponsive: '48-home-solar-responsive.css',
    retiredThemes: '50-retired-theme-previews.css',
    solarTheme: '60-theme-solar.css',
    services: '70-service-pages.css',
    homeReviews: '80-home-reviews.css'
};

const bundles = {
    'style.css': [
        modules.foundation,
        modules.sharedTail,
        modules.services
    ],
    'home.css': [
        modules.foundation,
        modules.solarShowcase,
        modules.homeSections,
        modules.sharedTail,
        modules.homeThemeMain,
        modules.sharedFaq,
        modules.homeThemeFooter,
        modules.homeSolarResponsive,
        modules.homeReviews
    ],
    'solar.css': [
        modules.foundation,
        modules.solarShowcase,
        modules.sharedTail,
        modules.sharedFaq,
        modules.homeSolarResponsive,
        modules.solarTheme,
        modules.services
    ]
};

function buildBundles() {
    for (const [bundleName, moduleFiles] of Object.entries(bundles)) {
        const banner = [
            '/*',
            ' * Generated by scripts/build-css.js.',
            ` * Modules: ${moduleFiles.join(', ')}`,
            ' * Edit public/css/modules/*.css and run npm run build:css.',
            ' */',
            ''
        ].join('\n');
        const content = moduleFiles
            .map((file) => fs.readFileSync(path.join(modulesDir, file), 'utf8').trim())
            .join('\n\n');
        fs.writeFileSync(path.join(cssDir, bundleName), `${banner}${content}\n`, 'utf8');
    }
}

buildBundles();

for (const [bundleName, moduleFiles] of Object.entries(bundles)) {
    const bytes = fs.statSync(path.join(cssDir, bundleName)).size;
    console.log(`${bundleName}: ${bytes} bytes (${moduleFiles.length} modules)`);
}
